export function localizeCoachText(text: string, language: Language, poseTitle?: string): string {
  if (language === 'en') return text;
  const exact = coachExact[text];
  if (exact) return exact;

  const matchStanding = text.match(/^Straighten your (left|right) standing leg\.$/);
  if (matchStanding) return `${matchStanding[1] === 'left' ? 'बाएँ' : 'दाएँ'} सहारे वाले पैर को सीधा करें।`;
  const matchBend = text.match(/^Bend your (left|right) knee and lift that foot\.$/);
  if (matchBend) return `${matchBend[1] === 'left' ? 'बाएँ' : 'दाएँ'} घुटने को मोड़ें और उस पैर को उठाएँ।`;
  const matchLift = text.match(/^Lift your (left|right) foot off the floor\.$/);
  if (matchLift) return `अपना ${matchLift[1] === 'left' ? 'बायाँ' : 'दायाँ'} पैर फर्श से उठाएँ।`;
  const matchCloser = text.match(/^Bring your (left|right) foot closer to the inner (left|right) leg\.$/);
  if (matchCloser) return `${matchCloser[2] === 'left' ? 'बाएँ' : 'दाएँ'} पैर की अंदरूनी ओर अपना ${matchCloser[1] === 'left' ? 'बायाँ' : 'दायाँ'} पैर पास लाएँ।`;
  const matchOpen = text.match(/^Open your (left|right) knee outward\.$/);
  if (matchOpen) return `${matchOpen[1] === 'left' ? 'बाएँ' : 'दाएँ'} घुटने को बाहर की ओर खोलें।`;
  const matchBendMore = text.match(/^Bend your (left|right) knee a little more\.$/);
  if (matchBendMore) return `${matchBendMore[1] === 'left' ? 'बाएँ' : 'दाएँ'} घुटने को थोड़ा और मोड़ें।`;
  const matchStraightenSlight = text.match(/^Straighten your (left|right) knee slightly\.$/);
  if (matchStraightenSlight) return `${matchStraightenSlight[1] === 'left' ? 'बाएँ' : 'दाएँ'} घुटने को थोड़ा सीधा करें।`;
  const matchRear = text.match(/^Straighten your (left|right) rear leg\.$/);
  if (matchRear) return `${matchRear[1] === 'left' ? 'बाएँ' : 'दाएँ'} पीछे वाले पैर को सीधा करें।`;
  const matchReachDown = text.match(/^Reach your (left|right) hand farther down the (left|right) leg\.$/);
  if (matchReachDown) return `${matchReachDown[1] === 'left' ? 'बाएँ' : 'दाएँ'} हाथ को ${matchReachDown[2] === 'left' ? 'बाएँ' : 'दाएँ'} पैर के साथ नीचे की ओर और बढ़ाएँ।`;
  const matchReachUp = text.match(/^Reach your (left|right) arm upward above the shoulder\.$/);
  if (matchReachUp) return `${matchReachUp[1] === 'left' ? 'बाएँ' : 'दाएँ'} हाथ को कंधे से ऊपर उठाएँ।`;
  return text;
}

export function localizedCoachStart(poseTitle: string, steps: string[], language: Language) {
  if (language === 'en') return `${poseTitle}. ${steps.slice(0, 3).join('. ')}`;
  return `${poseTitle}। ${steps.slice(0, 3).join(' ')}`;
}
